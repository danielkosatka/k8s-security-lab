"""labcheck.py - connectivity dashboard for the k8s security lab.

Checks every node in parallel:
  PING  - does the VM answer ICMP on the lab network (VMnet2)?
  SSH   - is TCP port 22 open (OpenSSH running)?
  K3S   - is TCP port 6443 open (Kubernetes API, control plane only)?

Usage (Git Bash or PowerShell):
  python scripts/labcheck.py            # check once
  python scripts/labcheck.py --watch 5  # refresh every 5 seconds (Ctrl+C to stop)

Exit code is 0 if every required check passes, 1 otherwise (handy for CI later).
Standard library only: no pip installs needed.
"""
import argparse
import os
import platform
import socket
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

# name -> (lab IP, role)
NODES = {
    "k8s-cp": ("192.168.100.10", "control-plane"),
    "k8s-w1": ("192.168.100.11", "worker"),
    "k8s-w2": ("192.168.100.12", "worker"),
    "obs":    ("192.168.100.20", "monitoring"),
}

GREEN, RED, GREY, BOLD, RESET = "\033[92m", "\033[91m", "\033[90m", "\033[1m", "\033[0m"
IS_WINDOWS = platform.system() == "Windows"


def ping(ip: str) -> bool:
    """Send one ICMP echo with a 1-second timeout. True if the host replied."""
    if IS_WINDOWS:
        cmd = ["ping", "-n", "1", "-w", "1000", ip]
    else:
        cmd = ["ping", "-c", "1", "-W", "1", ip]
    result = subprocess.run(cmd, capture_output=True, text=True)
    # Windows returns 0 even for "Destination host unreachable", so check the text too
    return result.returncode == 0 and "TTL=" in result.stdout.upper()


def port_open(ip: str, port: int, timeout: float = 1.0) -> bool:
    """Try a TCP connection. True if something is listening on that port."""
    try:
        with socket.create_connection((ip, port), timeout=timeout):
            return True
    except OSError:
        return False


def check_node(name: str) -> dict:
    ip, role = NODES[name]
    k3s = port_open(ip, 6443) if role == "control-plane" else None
    return {"name": name, "ip": ip, "role": role,
            "ping": ping(ip), "ssh": port_open(ip, 22), "k3s": k3s}


def cell(value) -> str:
    if value is None:
        return f"{GREY}  -   {RESET}"
    return f"{GREEN}  UP  {RESET}" if value else f"{RED} DOWN {RESET}"


def write_status(results: list, path: str) -> None:
    """Write the results as a Markdown note (shown on the Obsidian vault homepage)."""
    def icon(value) -> str:
        if value is None:
            return "➖"                                   # grey dash: not applicable
        return "\U0001F7E2" if value else "\U0001F534"      # green / red circle

    up = sum(r["ping"] for r in results)
    lines = [
        "---", "tags: [homelab, generated]", "status: generated", "---",
        f"**{up}/{len(results)} nodes reachable** · last checked {datetime.now():%Y-%m-%d %H:%M:%S}",
        "",
        "| Node | IP | Role | Ping | SSH | K3s API |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r['name']} | {r['ip']} | {r['role']} | "
                     f"{icon(r['ping'])} | {icon(r['ssh'])} | {icon(r['k3s'])} |")
    lines += ["", "*Generated by `labcheck.py`. Don't edit by hand.*", ""]
    try:
        Path(path).write_text("\n".join(lines), encoding="utf-8")
    except OSError as err:  # e.g. vault drive not connected: keep the dashboard running
        print(f"{GREY}could not write status file: {err}{RESET}")


def run_checks(require_k3s: bool, status_file: str | None = None) -> bool:
    with ThreadPoolExecutor(max_workers=len(NODES)) as pool:
        results = list(pool.map(check_node, NODES))

    print(f"{BOLD}k8s security lab  -  {datetime.now():%Y-%m-%d %H:%M:%S}{RESET}")
    print(f"{'NODE':<8} {'IP':<16} {'ROLE':<14} PING   SSH    K3S")
    all_ok = True
    for r in results:
        print(f"{r['name']:<8} {r['ip']:<16} {r['role']:<14}"
              f"{cell(r['ping'])} {cell(r['ssh'])} {cell(r['k3s'])}")
        if not (r["ping"] and r["ssh"]):
            all_ok = False
        if require_k3s and r["k3s"] is False:
            all_ok = False

    up = sum(r["ping"] for r in results)
    colour = GREEN if all_ok else RED
    print(f"{colour}{up}/{len(results)} nodes reachable{RESET}")
    if status_file:
        write_status(results, status_file)
    return all_ok


def main() -> int:
    parser = argparse.ArgumentParser(description="Check connectivity of the lab nodes.")
    parser.add_argument("--watch", type=int, metavar="SECONDS",
                        help="keep refreshing every SECONDS (Ctrl+C to stop)")
    parser.add_argument("--require-k3s", action="store_true",
                        help="treat a closed k3s API port as a failure (use once k3s is installed)")
    parser.add_argument("--status-file", metavar="PATH",
                        help="also write the results to a Markdown file (e.g. a note in an Obsidian vault)")
    args = parser.parse_args()

    if IS_WINDOWS:
        os.system("")  # switches on colour (ANSI) support in older Windows consoles
    print("\033]0;k8s lab check\007", end="")  # sets the window title

    if not args.watch:
        return 0 if run_checks(args.require_k3s, args.status_file) else 1
    try:
        while True:
            print("\033[2J\033[H", end="")  # clear screen, cursor to top-left
            run_checks(args.require_k3s, args.status_file)
            print(f"{GREY}refreshing every {args.watch}s - Ctrl+C to stop{RESET}")
            time.sleep(args.watch)
    except KeyboardInterrupt:
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
